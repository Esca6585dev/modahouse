"use client";

import { useRouter } from "next/navigation";
import { createContext, useCallback, useContext, useEffect, useState } from "react";
import { errorMessage } from "@/lib/api";
import { useAuth } from "@/lib/auth";
import { absUrl, copyText, downloadPin, fetchShareCard, shareCardFile } from "@/lib/share";
import type { Pin } from "@/lib/types";
import ChatPicker from "./chat/ChatPicker";
import { DotsIcon, DownloadIcon, ImagesIcon, LinkIcon, SendIcon, TelegramIcon, WhatsappIcon } from "./Icons";
import Modal from "./Modal";
import { useToast } from "./Toast";

type Target = { pin: Pin; index: number };
type OpenShare = (pin: Pin, index?: number) => void;

const ShareContext = createContext<OpenShare>(() => {});

/** Opens the share sheet of a post: `useShare()(pin, carouselIndex)`. */
export const useShare = () => useContext(ShareContext);

export function ShareProvider({ children }: { children: React.ReactNode }) {
  const [target, setTarget] = useState<Target | null>(null);
  const open = useCallback<OpenShare>((pin, index = 0) => setTarget({ pin, index }), []);
  return (
    <ShareContext.Provider value={open}>
      {children}
      {target && <ShareSheet key={target.pin.id} pin={target.pin} index={target.index} onClose={() => setTarget(null)} />}
    </ShareContext.Provider>
  );
}

type Busy = "" | "card" | "download" | "more";

/**
 * Pinterest-style share sheet: a preview of the branded share card (generated by the server) and
 * big round buttons for the link, WhatsApp, Telegram, sharing the card image, download and the system sheet.
 */
export default function ShareSheet({ pin, index = 0, onClose }: { pin: Pin; index?: number; onClose: () => void }) {
  const toast = useToast();
  const router = useRouter();
  const { user } = useAuth();
  const [picking, setPicking] = useState(false);
  const [card, setCard] = useState<File | null>(null);
  const [preview, setPreview] = useState("");
  const [cardError, setCardError] = useState<string | null>(null);
  const [attempt, setAttempt] = useState(0);
  const [busy, setBusy] = useState<Busy>("");
  const path = `/pin/${pin.id}`;
  const url = absUrl(path);
  const message = `${pin.title} — ModaHouse`;
  const cover = pin.images[0];
  const coverUrl = cover?.type === "video" ? cover.posterUrl || pin.imageUrl : cover?.url || pin.imageUrl;

  // Generate the card as soon as the sheet opens: sharing a file must happen right in the tap,
  // so it has to be ready by then.
  useEffect(() => {
    const ctl = new AbortController();
    let objectUrl = "";
    setCardError(null);
    fetchShareCard(pin.id, ctl.signal).then(
      (file) => {
        objectUrl = URL.createObjectURL(file);
        setCard(file);
        setPreview(objectUrl);
      },
      (e) => {
        if ((e as Error).name !== "AbortError") setCardError(errorMessage(e));
      },
    );
    return () => {
      ctl.abort();
      if (objectUrl) URL.revokeObjectURL(objectUrl);
    };
  }, [pin.id, attempt]);

  const done = (msg: string | null) => {
    if (msg) toast(msg);
    onClose();
  };

  const run = async (kind: Busy, fn: () => Promise<string | null>) => {
    setBusy(kind);
    try {
      done(await fn());
    } catch (e) {
      toast(errorMessage(e), "error");
    } finally {
      setBusy("");
    }
  };

  const copyLink = async () => done((await copyText(url)) ? "Baglanyşyk göçürildi" : null);

  const more = () => run("more", async () => {
    if (typeof navigator.share === "function") {
      try {
        await navigator.share({ title: pin.title, text: message, url });
        return null;
      } catch (e) {
        if ((e as Error).name === "AbortError") return null;
      }
    }
    return (await copyText(url)) ? "Baglanyşyk göçürildi" : null;
  });

  const isVideo = pin.images[index]?.type === "video";
  const loading = !card && !cardError;

  const sendInChat = () => {
    if (!user) {
      onClose();
      router.push(`/login?next=${encodeURIComponent(window.location.pathname + window.location.search)}`);
      return;
    }
    setPicking(true);
  };

  if (picking) {
    return (
      <Modal title="Habar bilen ugrat" onClose={onClose}>
        <ChatPicker mode="share" pin={pin} onDone={onClose} />
      </Modal>
    );
  }

  return (
    <Modal title="Paýlaş" onClose={onClose}>
      <div className="share-sheet">
        <div className="ss-stage">
          <div className={`ss-card ${loading ? "loading" : ""}`} aria-busy={loading}>
            {preview ? (
              // eslint-disable-next-line @next/next/no-img-element
              <img src={preview} alt={`${pin.title}: paýlaşmak üçin surat`} />
            ) : (
              <>
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={coverUrl} alt="" className="ss-cover" />
                <div className="ss-state" role="status">
                  {cardError ? (
                    <>
                      <span>Surat taýýarlanmady</span>
                      <button type="button" className="btn btn-secondary btn-sm" onClick={() => setAttempt((n) => n + 1)}>Gaýtadan synanyş</button>
                    </>
                  ) : (
                    <>
                      <span className="spinner" aria-hidden />
                      <span>Surat taýýarlanýar…</span>
                    </>
                  )}
                </div>
              </>
            )}
          </div>
        </div>

        <div className="ss-grid">
          <button type="button" className="ss-btn" onClick={sendInChat}>
            <span className="ss-icon brand"><SendIcon size={25} /></span>
            <span>Habar bilen ugrat</span>
          </button>
          <button type="button" className="ss-btn" onClick={copyLink}>
            <span className="ss-icon grey"><LinkIcon size={26} /></span>
            <span>Baglanyşygy göçür</span>
          </button>
          <a
            className="ss-btn"
            href={`https://wa.me/?text=${encodeURIComponent(`${message} ${url}`)}`}
            target="_blank"
            rel="noopener noreferrer"
            onClick={onClose}
          >
            <span className="ss-icon whatsapp"><WhatsappIcon size={28} /></span>
            <span>WhatsApp</span>
          </a>
          <a
            className="ss-btn"
            href={`https://t.me/share/url?url=${encodeURIComponent(url)}&text=${encodeURIComponent(message)}`}
            target="_blank"
            rel="noopener noreferrer"
            onClick={onClose}
          >
            <span className="ss-icon telegram"><TelegramIcon size={27} /></span>
            <span>Telegram</span>
          </a>
          <button
            type="button"
            className="ss-btn"
            disabled={!card || busy !== ""}
            onClick={() => card && run("card", () => shareCardFile(card, pin.title, path))}
            aria-busy={loading || busy === "card"}
          >
            <span className="ss-icon brand">{loading || busy === "card" ? <span className="spinner light" aria-hidden /> : <ImagesIcon size={26} />}</span>
            <span>Surat bilen paýlaş</span>
          </button>
          <button
            type="button"
            className="ss-btn"
            disabled={busy !== ""}
            onClick={() => run("download", () => downloadPin(pin.id, index))}
            aria-busy={busy === "download"}
          >
            <span className="ss-icon grey">{busy === "download" ? <span className="spinner" aria-hidden /> : <DownloadIcon size={26} />}</span>
            <span>{isVideo ? "Wideony ýükle" : "Ýükle"}</span>
          </button>
          <button type="button" className="ss-btn" disabled={busy !== ""} onClick={more}>
            <span className="ss-icon grey"><DotsIcon size={26} /></span>
            <span>Başga…</span>
          </button>
        </div>
      </div>
    </Modal>
  );
}
